const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/utils/recordEditing.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const api = {};
new Function('exports', compiled)(api);
const { fieldsFor, displayValue, buildRecordPatch } = api;
const original = { vacunaId: 7, pacienteId: 3, nombre: 'Vacuna', fechaaplicacion: '2026-09-21T13:20:00.000Z', lote: 'A', archivoBase64: 'preserve' };
const draft = Object.fromEntries(fieldsFor('vacuna').map(f => [f.key, displayValue(original[f.key], f)]));
assert.deepEqual(buildRecordPatch('vacuna', original, draft), {});
assert.deepEqual(buildRecordPatch('vacuna', original, { ...draft, nombre: 'Actualizada', pacienteId: '99', archivoBase64: 'overwrite' }), { nombre: 'Actualizada' });
assert.deepEqual(buildRecordPatch('vacuna', original, { ...draft, fechaaplicacion: '2026-09-22' }), { fechaaplicacion: '2026-09-22T13:20:00.000Z' });
assert.throws(() => buildRecordPatch('vacuna', original, { ...draft, fechaaplicacion: '2026-02-30' }));
assert.throws(() => buildRecordPatch('vacuna', original, { ...draft, nombre: ' ' }));
assert.deepEqual(buildRecordPatch('habitoespecifico', {}, { cantidad: '0' }), { cantidad: 0 });
assert.deepEqual(buildRecordPatch('habitoespecifico', {}, { cantidad: '2.5' }), { cantidad: 2.5 });
assert.throws(() => buildRecordPatch('habitoespecifico', {}, { cantidad: 'NaN' }));
assert.deepEqual(buildRecordPatch('unknown', {}, { pacienteId: '99' }), {});
console.log('Record editing: 9 assertions passed.');
